"""Pre-record the game's fixed lines with the Kokoro neural voice.

Usage (from the game folder):
  tools/voice/.venv/bin/python tools/voice/render.py tools/voice/lines.json

lines.json comes from allSpeech() in engine.js: [{"key": "1a2b3c4d", "text": "..."}]. To make it, open
the game in a browser, run copy(JSON.stringify(allSpeech())) in the console and paste into the file.
A clip is keyed by its exact text, so after editing any spoken line, re-export and re-render or
that line falls back to the browser voice.
Each line becomes voice/<key>.m4a; voice/index.js then lists every recorded key so the
game plays the recording instead of the browser voice. Existing clips are skipped, so
re-running after adding a level only renders the new lines.
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

import soundfile as sf
from kokoro_onnx import Kokoro

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(GAME, 'voice')
VOICE, SPEED, LANG = 'bf_emma', 0.92, 'en-gb'

# Words the voice gets wrong, spelled the way they should sound.
SAY_AS = {
    r'\bvs\b': 'versus',
    r'\bH\. pylori\b': 'aitch pie-lor-eye',
    r'\bC\. diff\b': 'see diff',
    r'\bClostridioides difficile\b': 'clos-trid-ee-oy-deez diffi-seel',
    r'\bstercobilin\b': 'stur-co-bye-lin',
    r'\bskatole\b': 'skat-ole',
    r'\bindole\b': 'in-dole',
    r'\bpili\b': 'pie-lie',
    r'\bvilli\b': 'vill-eye',
    r'\boesophagus\b': 'ee-sof-a-gus',
    r'\bdiarrhoea\b': 'die-a-ree-a',
    r'\bhaemoglobin\b': 'hee-mo-glow-bin',
    r'\bfaecal\b': 'fee-cal',
    r'\bpapillomavirus\b': 'pap-ill-oh-ma virus',
    r'\bpapilloma\b': 'pap-ill-oh-ma',
    r'\bpapilla\b': 'pap-ill-a',
    r'\bsalicylic\b': 'sal-ih-sil-ik',
    r'\bLangerhans\b': 'lang-er-hans',
    r'\bicosahedron\b': 'eye-koss-a-hee-dron',
    r'\bverruca\b': 'ver-roo-ka',
    r'\bvulgaris\b': 'vul-gar-iss',
    r'\bHPV\b': 'aitch pee vee',
    r'\brhinovirus(es)?\b': r'rye-no-virus\1',
    r'\bneutrophils?\b': lambda m: 'new-tro-fill' + ('s' if m.group(0).lower().endswith('s') else ''),
    r'\bturbinates?\b': lambda m: 'tur-bin-ut' + ('s' if m.group(0).lower().endswith('s') else ''),
    r'\bcilia\b': 'silly-a',
    r'\btrigeminal\b': 'try-jem-in-al',
    r'\bIgA\b': 'eye jee ay',
    r'\bsaline\b': 'say-line',
}


def say_as(text):
    for pat, rep in SAY_AS.items():
        text = re.sub(pat, rep, text, flags=re.IGNORECASE)
    return text


def main(lines_path):
    lines = json.load(open(lines_path))
    os.makedirs(OUT, exist_ok=True)
    tts = Kokoro(os.path.join(HERE, 'models', 'kokoro-v1.0.int8.onnx'), os.path.join(HERE, 'models', 'voices-v1.0.bin'))
    todo = [l for l in lines if not os.path.exists(os.path.join(OUT, l['key'] + '.m4a'))]
    print(f'{len(lines)} lines, {len(todo)} to render')
    for i, line in enumerate(todo, 1):
        samples, rate = tts.create(say_as(line['text']), voice=VOICE, speed=SPEED, lang=LANG)
        with tempfile.NamedTemporaryFile(suffix='.wav', delete=False) as tmp:
            sf.write(tmp.name, samples, rate)
        out = os.path.join(OUT, line['key'] + '.m4a')
        if shutil.which('afconvert'):  # macOS
            subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac', '-b', '48000', tmp.name, out], check=True)
        else:  # Linux: ffmpeg
            subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', tmp.name, '-c:a', 'aac', '-b:a', '48k', out], check=True)
        os.unlink(tmp.name)
        print(f'[{i}/{len(todo)}] {line["key"]} {line["text"][:60]}')
    keys = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith('.m4a'))
    with open(os.path.join(OUT, 'index.js'), 'w') as f:
        f.write('// Generated by tools/voice/render.py: lines that have a recorded clip in this folder.\n')
        f.write('window.VOICE_LINES = new Set(' + json.dumps(keys) + ');\n')
    print(f'voice/index.js lists {len(keys)} clips')


if __name__ == '__main__':
    main(sys.argv[1])
